# Forecast Mode
# ---------------------------------------------------------------------------

def run_forecast_mode(engine: IndiaFloodEngine, args) -> dict:
    """Run simulation using live weather forecast from Open-Meteo."""
    from data.weather_forecast import (
        fetch_point_forecast,
        fetch_spatial_forecast,
        interpolate_rainfall_to_grid,
        assess_flood_risk_from_forecast,
    )

    bbox = engine.bbox
    mid_lat = (bbox[1] + bbox[3]) / 2.0
    mid_lon = (bbox[0] + bbox[2]) / 2.0

    print(f"\n[WEB] Fetching weather forecast from Open-Meteo...")
    print(f"   Location: ({mid_lat:.3f}°N, {mid_lon:.3f}°E)")
    print(f"   Model: {engine.cfg['weather_model']}")

    # Single-point forecast for alert assessment
    fc = fetch_point_forecast(
        mid_lat, mid_lon,
        model=engine.cfg["weather_model"],
        forecast_days=engine.cfg.get("forecast_days", 3),
    )

    # Assess risk
    assessment = assess_flood_risk_from_forecast(fc, duration_hr=args.forecast_hours or 24)
    print(f"\n   {assessment['imd_alert']}")
    print(f"   Total: {assessment['total_rainfall_mm']} mm over {assessment['event_duration_hr']} hr")
    print(f"   Peak intensity: {assessment['peak_intensity_mm_hr']} mm/hr")

    if not assessment["suitable_for_simulation"]:
        print("\n   ⚠️  Insufficient rainfall for meaningful flood simulation")
        print("      (< 15 mm forecast). Simulation skipped.")
        return {"forecast": assessment, "skipped": True}

    rainfall_mm = assessment["total_rainfall_mm"]
    duration_hr = float(assessment["event_duration_hr"])

    # Spatial forecast (grid) for distributed rainfall
    print("\n   Fetching spatial rainfall grid...")
    try:
        spatial = fetch_spatial_forecast(
            bbox, engine.cfg["weather_model"],
            forecast_days=engine.cfg.get("forecast_days", 3),
        )
        print(f"   Spatial rainfall: mean={np.mean(spatial['rainfall_mm']):.1f}mm, "
              f"max={np.max(spatial['rainfall_mm']):.1f}mm")
    except Exception as e:
        logger.warning(f"Spatial forecast failed ({e}), using uniform rainfall")
        spatial = None

    # Run engine
    engine.load_terrain()
    engine.load_land_cover()
    engine.load_soils()
    engine.prepare_model_parameters()

    rainfall_grid = None
    if spatial:
        try:
            rainfall_grid = interpolate_rainfall_to_grid(
                spatial, engine.dem.shape, bbox
            )
        except Exception as e:
            logger.warning(f"Rainfall interpolation failed: {e}")

    engine.compute_flow_network()
    engine.compute_steady_discharge(rainfall_mm, duration_hr, rainfall_grid)
    engine.apply_partial_correction(duration_hr)
    engine.estimate_flood_depth()

    output_paths = engine.generate_outputs(rainfall_mm, duration_hr)

    return {
        "forecast": assessment,
        "output_paths": output_paths,
        "stats": engine.stats,
        "flood_depth": engine.flood_depth,
    }


