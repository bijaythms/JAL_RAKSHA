# ---------------------------------------------------------------------------
# Core Engine Class
# ---------------------------------------------------------------------------

class IndiaFloodEngine:
    """
    India Flood Inundation Engine.

    Implements the 5-step FastFlood algorithm adapted for Indian conditions:
    - SCS-CN runoff model (IS 5477 / NIH Roorkee parameters)
    - CWC India lag time and peak correction
    - ESA WorldCover 2021 land cover
    - SoilGrids HSG classification
    - SRTM / NASADEM / Copernicus DEM

    Parameters
    ----------
    bbox : tuple
        Bounding box (min_lon, min_lat, max_lon, max_lat) in WGS84
    output_dir : str
        Directory to save all outputs
    config : dict, optional
        Override default configuration values
    """

    def __init__(
        self,
        bbox: Tuple[float, float, float, float],
        output_dir: str = "outputs",
        config: dict = None,
    ):
        self.bbox = bbox
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

        # Merge config
        self.cfg = {**DEFAULT_CONFIG, **({} if config is None else config)}
        self.cfg["output_dir"] = str(self.output_dir)

        # State
        self.dem = None
        self.slope = None
        self.meta = None
        self.fdir = None
        self.acc = None
        self.lulc = None
        self.hsg = None
        self.cn = None
        self.manning_n = None
        self.Q_ss = None
        self.Q_peak = None
        self.flood_depth = None
        self.velocity = None
        self.hand = None
        self.stats = None
        self.dx = self.dy = 30.0  # Default cell size (updated from meta)

        logger.info(f"India Flood Engine initialized")
        logger.info(f"  Bounding box: {bbox}")
        logger.info(f"  Output dir:   {self.output_dir}")

    # ──────────────────────────────────────────────────────────────────────
    # Data Loading
    # ──────────────────────────────────────────────────────────────────────

    def load_terrain(self) -> None:
        """Download and condition DEM (Step 1)."""
        from data.dem_downloader import get_dem, generate_synthetic_dem
        from engine.dem_processor import condition_terrain, get_cell_size

        print("\n[DATA] [Step 1/5] Loading terrain data...")
        t0 = time.time()

        # Download DEM
        dem_dir = str(self.output_dir / "dem")
        if self.cfg.get("use_synthetic_dem"):
            dem_raw_path = str(self.output_dir / "dem" / "dem_synthetic.tif")
            generate_synthetic_dem(self.bbox, dem_raw_path)
        else:
            dem_raw_path = get_dem(
                self.bbox, dem_dir,
                dem_type=self.cfg["dem_type"],
                api_key=self.cfg.get("api_key"),
                use_synthetic_fallback=True,
            )

        # Hydro-condition the DEM
        self.dem, self.slope, self.meta = condition_terrain(
            dem_raw_path,
            str(self.output_dir / "terrain"),
            use_pysheds=self.cfg.get("use_pysheds", True),
        )

        # Get cell size in metres
        self.dx, self.dy = get_cell_size(self.meta)
        logger.info(f"Cell size: {self.dx:.1f}m × {self.dy:.1f}m")
        print(f"   [OK] DEM loaded: {self.dem.shape[0]}×{self.dem.shape[1]} cells "
              f"({self.dx:.0f}m res) [{time.time()-t0:.1f}s]")

    def load_land_cover(self) -> None:
        """Load ESA WorldCover 2021 LULC data."""
        from data.landcover_loader import get_worldcover_for_bbox, generate_synthetic_lulc

        print("[MAP]  Loading land cover (ESA WorldCover 2021)...")
        t0 = time.time()

        if self.cfg.get("use_synthetic_lulc"):
            self.lulc = generate_synthetic_lulc(self.dem.shape, self.bbox)
        else:
            lulc_dir = str(self.output_dir / "landcover")
            try:
                self.lulc = get_worldcover_for_bbox(
                    self.bbox, lulc_dir,
                    target_shape=self.dem.shape,
                    target_meta=self.meta,
                )
            except Exception as e:
                logger.warning(f"WorldCover download failed ({e}). Using synthetic LULC.")
                self.lulc = generate_synthetic_lulc(self.dem.shape, self.bbox)

        print(f"   [OK] Land cover loaded [{time.time()-t0:.1f}s]")

    def load_soils(self) -> None:
        """Load soil HSG data from SoilGrids."""
        from data.soil_loader import generate_hsg_grid, get_default_hsg_grid

        print("[SOIL] Loading soil data (SoilGrids HSG)...")
        t0 = time.time()

        if self.cfg.get("use_default_soil"):
            # Default to HSG-B (most common in India)
            self.hsg = get_default_hsg_grid(self.dem.shape, default_hsg=1)
        else:
            try:
                hsg_path = str(self.output_dir / "terrain" / "hsg.tif")
                self.hsg = generate_hsg_grid(
                    self.bbox, self.dem.shape,
                    output_path=hsg_path, meta=self.meta,
                    api_sample_points=4,
                )
            except Exception as e:
                logger.warning(f"SoilGrids failed ({e}). Using default HSG-B.")
                self.hsg = get_default_hsg_grid(self.dem.shape, default_hsg=1)

        print(f"   [OK] Soil HSG loaded [{time.time()-t0:.1f}s]")

    def prepare_model_parameters(self) -> None:
        """Compute CN grid and Manning's n grid from LULC + soil."""
        from india_params.cn_table import get_cn_grid, amc_from_5day_rainfall
        from india_params.manning_table import get_manning_grid

        print("[CFG]  Computing model parameters (CN, Manning's n)...")
        t0 = time.time()

        amc = self.cfg.get("amc", "II")
        self.cn = get_cn_grid(self.lulc, self.hsg, amc=amc)
        self.manning_n = get_manning_grid(self.lulc)

        logger.info(f"CN grid: mean={np.nanmean(self.cn):.1f}, "
                    f"min={np.nanmin(self.cn):.0f}, max={np.nanmax(self.cn):.0f}")
        logger.info(f"Manning's n: mean={np.nanmean(self.manning_n):.3f}")
        print(f"   [OK] Parameters ready (mean CN={np.nanmean(self.cn):.0f}) [{time.time()-t0:.1f}s]")

    # ──────────────────────────────────────────────────────────────────────
    # Steps 2 & 3: Flow Routing + Discharge
    # ──────────────────────────────────────────────────────────────────────

    def compute_flow_network(self) -> None:
        """Compute D8 flow direction and accumulation (Step 2)."""
        from engine.flow_router import (
            compute_flow_direction_numpy,
            compute_flow_accumulation,
            extract_stream_network,
        )

        print("\n[FLOOD] [Step 2/5] Computing flow network (D8 routing)...")
        t0 = time.time()

        # Try pysheds first for large grids
        if self.cfg.get("use_pysheds") and self.dem.size > 10000:
            try:
                from pysheds.grid import Grid
                conditioned_path = str(self.output_dir / "terrain" / "dem_fsa.tif")
                if Path(conditioned_path).exists():
                    grid = Grid.from_raster(conditioned_path)
                    dem_ps = grid.read_raster(conditioned_path)
                    fdir_ps = grid.flowdir(dem_ps)
                    self.fdir = np.array(fdir_ps).astype(np.int16)
                    acc_ps = grid.accumulation(fdir_ps)
                    cell_area = self.dx * self.dy
                    self.acc = np.array(acc_ps, dtype=np.float64) * cell_area
                    logger.info("Flow routing via pysheds")
                    self._stream_mask = extract_stream_network(
                        self.acc, self.cfg["stream_threshold_km2"], cell_area
                    )
                    print(f"   [OK] Flow network (pysheds) [{time.time()-t0:.1f}s]")
                    return
            except Exception as e:
                logger.warning(f"pysheds routing failed ({e}), using numpy fallback")

        # Numpy fallback
        self.fdir = compute_flow_direction_numpy(self.dem)
        cell_area = self.dx * self.dy
        self.acc = compute_flow_accumulation(self.fdir, cell_area)
        self._stream_mask = extract_stream_network(
            self.acc, self.cfg["stream_threshold_km2"], cell_area
        )
        print(f"   [OK] Flow network (numpy) [{time.time()-t0:.1f}s]")

    def compute_steady_discharge(
        self,
        rainfall_mm: float,
        duration_hr: float,
        rainfall_grid: np.ndarray = None,
    ) -> None:
        """Compute steady-state discharge (Step 3)."""
        from engine.runoff_model import rainfall_to_effective_rate
        from engine.flow_router import compute_steady_discharge
        from india_params.monsoon_regions import get_intensity_factor, get_region_for_point

        print(f"\n[Q] [Step 3/5] Computing steady-state discharge "
              f"(rain={rainfall_mm:.0f}mm, dur={duration_hr:.1f}hr)...")
        t0 = time.time()

        # Get regional intensity correction
        mid_lat = (self.bbox[1] + self.bbox[3]) / 2.0
        mid_lon = (self.bbox[0] + self.bbox[2]) / 2.0
        region = get_region_for_point(mid_lat, mid_lon)
        intensity_factor = region.runoff_intensity_factor

        amc = self.cfg.get("amc", "II")

        # If spatial rainfall grid provided (from forecast), use it per cell
        if rainfall_grid is not None and rainfall_grid.shape == self.dem.shape:
            runoff_mm, q_eff = rainfall_to_effective_rate(
                rainfall_grid, duration_hr, self.cn, amc, 0.1, intensity_factor
            )
        else:
            runoff_mm, q_eff = rainfall_to_effective_rate(
                rainfall_mm, duration_hr, self.cn, amc, 0.1, intensity_factor
            )

        self.Q_ss = compute_steady_discharge(self.acc, float(np.nanmean(q_eff)))
        self._runoff_mm = runoff_mm
        self._intensity_factor = intensity_factor
        self._region = region

        print(f"   [OK] Discharge computed (max={np.max(self.Q_ss):.1f} m³/s, "
              f"region={region.name}) [{time.time()-t0:.1f}s]")

    # ──────────────────────────────────────────────────────────────────────
    # Step 4: Partial Steady-State Correction
    # ──────────────────────────────────────────────────────────────────────

    def apply_partial_correction(self, duration_hr: float) -> None:
        """Apply partial steady-state correction (Step 4)."""
        from engine.partial_correction import apply_partial_ss_correction

        print("\n[CORR] [Step 4/5] Applying partial steady-state correction...")
        t0 = time.time()

        self.Q_peak = apply_partial_ss_correction(
            self.Q_ss, self.fdir, self.acc, self.cn, self.slope,
            self.dx, self.dy,
            event_duration_hr=duration_hr,
            region_factor=getattr(self, "_intensity_factor", 1.0),
            cell_area_m2=self.dx * self.dy,
        )
        print(f"   [OK] Peak discharge: max={np.max(self.Q_peak):.2f} m³/s "
              f"[{time.time()-t0:.1f}s]")

    # ──────────────────────────────────────────────────────────────────────
    # Step 5: Depth Estimation
    # ──────────────────────────────────────────────────────────────────────

    def estimate_flood_depth(self) -> None:
        """Estimate flood depth via Manning's inversion + HAND (Step 5)."""
        from engine.depth_estimator import estimate_flood_depth

        print("\n[MAP]  [Step 5/5] Reconstructing flood depth (Manning's + HAND)...")
        t0 = time.time()

        # Determine India region for hydraulic geometry
        mid_lat = (self.bbox[1] + self.bbox[3]) / 2.0
        mid_lon = (self.bbox[0] + self.bbox[2]) / 2.0
        region_key = _get_hg_region_key(mid_lat, mid_lon)

        self.flood_depth, self.velocity, self.hand = estimate_flood_depth(
            Q_peak=self.Q_peak,
            dem=self.dem,
            slope=self.slope,
            acc=self.acc,
            fdir=self.fdir,
            manning_n=self.manning_n,
            stream_mask=self._stream_mask,
            dx=self.dx, dy=self.dy,
            region=region_key,
            fast_hand=self.cfg.get("fast_hand", True),
        )
        print(f"   [OK] Flood map complete: max depth={np.max(self.flood_depth):.2f}m, "
              f"max vel={np.max(self.velocity):.2f}m/s [{time.time()-t0:.1f}s]")

    # ──────────────────────────────────────────────────────────────────────
    # Output Generation
    # ──────────────────────────────────────────────────────────────────────

    def generate_outputs(self, rainfall_mm: float, duration_hr: float) -> dict:
        """Save all outputs and generate reports."""
        from engine.inundation_mapper import (
            classify_risk,
            compute_summary_statistics,
            save_flood_outputs,
            save_simulation_report,
            print_summary,
        )

        print("\n[SAVE] Generating outputs...")

        risk = classify_risk(self.flood_depth)
        self.stats = compute_summary_statistics(
            self.flood_depth, self.velocity, risk,
            self.meta, rainfall_mm, duration_hr,
        )

        # Save GeoTIFFs
        output_paths = {}
        if self.cfg.get("save_geotiff"):
            output_paths.update(save_flood_outputs(
                self.flood_depth, self.velocity, self.hand, risk,
                self.meta, str(self.output_dir), prefix="flood",
            ))

        # Static PNG map (depth + risk + velocity panels, dark theme)
        if self.cfg.get("save_png_map"):
            from visualization.flood_map_plot import plot_flood_depth
            png_path = str(self.output_dir / "flood_map.png")
            plot_flood_depth(
                self.flood_depth, self.bbox, png_path,
                title="India Flood Inundation Engine",
                rainfall_mm=rainfall_mm, duration_hr=duration_hr,
                velocity=self.velocity,
            )
            output_paths["png_map"] = png_path
            print(f"   [OK] Static PNG map:   {png_path}")

        # Interactive HTML map (Google Hybrid + ESRI + depth/risk overlays)
        if self.cfg.get("save_html_map"):
            from visualization.flood_map_plot import create_interactive_map
            html_path = str(self.output_dir / "flood_map_interactive.html")
            create_interactive_map(
                self.flood_depth, self.bbox, html_path,
                velocity=self.velocity,
                default_basemap="google_hybrid",
                stats=self.stats,
                rainfall_mm=rainfall_mm,
                duration_hr=duration_hr,
                title="India Flood Inundation Engine",
            )
            output_paths["html_map"] = html_path
            print(f"   [OK] Interactive map: {html_path}")

        # JSON report
        report_path = save_simulation_report(self.stats, str(self.output_dir))
        output_paths["json_report"] = report_path

        print_summary(self.stats)
        return output_paths

    # ──────────────────────────────────────────────────────────────────────
    # Full Pipeline
    # ──────────────────────────────────────────────────────────────────────

    def run(
        self,
        rainfall_mm: float,
        duration_hr: float,
        rainfall_grid: np.ndarray = None,
    ) -> dict:
        """
        Run the complete 5-step flood simulation pipeline.

        Args:
            rainfall_mm: Total event rainfall (mm)
            duration_hr: Event duration (hours)
            rainfall_grid: Optional spatially distributed rainfall (mm), same shape as DEM

        Returns:
            Dict of output file paths and simulation stats
        """
        t_total = time.time()
        print("\n" + "=" * 65)
        print("  [RAIN]  INDIA FLOOD INUNDATION ENGINE — SIMULATION RUNNING")
        print("=" * 65)

        # Load data
        self.load_terrain()
        self.load_land_cover()
        self.load_soils()
        self.prepare_model_parameters()

        # Run 5-step algorithm
        self.compute_flow_network()
        self.compute_steady_discharge(rainfall_mm, duration_hr, rainfall_grid)
        self.apply_partial_correction(duration_hr)
        self.estimate_flood_depth()

        # Outputs
        output_paths = self.generate_outputs(rainfall_mm, duration_hr)

        elapsed = time.time() - t_total
        print(f"[DONE] Simulation complete in {elapsed:.1f} seconds\n")

        return {
            "output_paths": output_paths,
            "stats": self.stats,
            "flood_depth": self.flood_depth,
            "velocity": self.velocity,
            "hand": self.hand,
        }


# ---------------------------------------------------------------------------
# Helper: Get hydraulic geometry region key from lat/lon
# ---------------------------------------------------------------------------

def _get_hg_region_key(lat: float, lon: float) -> str:
    """Map lat/lon to hydraulic geometry region for India."""
    if lat > 28.0 and 74.0 <= lon <= 90.0:
        return "himalayan"
    elif 22.0 <= lat <= 28.5 and 74.0 <= lon <= 88.0:
        return "indo_gangetic"
    elif lat < 20.0 and 73.0 <= lon <= 80.0:
        return "peninsular"
    elif lon < 76.0 and lat < 22.0:
        return "western_ghats"
    elif lon > 89.0:
        return "northeast"
    return "default"


