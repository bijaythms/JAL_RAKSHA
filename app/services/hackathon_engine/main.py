# ---------------------------------------------------------------------------

def main():
    args = parse_args()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    # Interactive mode
    if args.mode == "interactive" and not args.demo:
        args = interactive_prompt(args)

    # Demo mode
    if args.demo:
        args.mode = "manual"
        args.no_download = True
        args.rain = args.rain or 150.0
        args.dur = args.dur or 12.0
        args.bbox = args.bbox or [80.8, 26.7, 81.2, 27.1]
        print("\n[DEMO] Running DEMO with synthetic data...")
        print(f"   Location: Lucknow area, Uttar Pradesh")
        print(f"   Rainfall: {args.rain}mm over {args.dur}hr (Very Heavy Rain)")

    # Validate bbox
    bbox = tuple(args.bbox or DEFAULT_CONFIG["bbox"])

    # Build config
    config = {
        "amc":                args.amc if hasattr(args, "amc") else "II",
        "dem_type":           args.dem_type if hasattr(args, "dem_type") else "nasadem",
        "weather_model":      args.weather_model if hasattr(args, "weather_model") else "ecmwf_ifs025",
        "forecast_days":      3,
        "stream_threshold_km2": args.stream_threshold if hasattr(args, "stream_threshold") else 1.0,
        "use_synthetic_dem":  getattr(args, "no_download", False),
        "use_synthetic_lulc": getattr(args, "no_download", False),
        "use_default_soil":   getattr(args, "no_download", False),
        "save_geotiff":       True,
        "save_html_map":      True,
        "save_png_map":       True,
    }

    # Initialise engine
    engine = IndiaFloodEngine(
        bbox=bbox,
        output_dir=args.output_dir if hasattr(args, "output_dir") else "outputs",
        config=config,
    )

    # Route to appropriate mode
    mode = getattr(args, "mode", "manual")
    try:
        if mode == "forecast":
            result = run_forecast_mode(engine, args)
        elif mode == "historical":
            if not (getattr(args, "start_date", None) and getattr(args, "end_date", None)):
                print("[ERR] --start-date and --end-date required for historical mode")
                sys.exit(1)
            result = run_historical_mode(engine, args)
        else:
            # Manual mode
            rainfall_mm = getattr(args, "rain", None) or DEFAULT_CONFIG["rainfall_mm"]
            duration_hr = getattr(args, "dur", None) or DEFAULT_CONFIG["duration_hr"]
            result = engine.run(rainfall_mm=rainfall_mm, duration_hr=duration_hr)

        # Print output locations
        if "output_paths" in result:
            print("\n[DIR] Output files:")
            for name, path in result["output_paths"].items():
                print(f"   {name:15s}: {path}")

    except KeyboardInterrupt:
        print("\n\nSimulation cancelled by user.")
        sys.exit(0)
    except Exception as e:
        logger.exception(f"Simulation failed: {e}")
        print(f"\n[ERR] Error: {e}")
        print("   Try running with --demo for a quick test with synthetic data.")
        sys.exit(1)


if __name__ == "__main__":
    main()
