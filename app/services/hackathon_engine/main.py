def interactive_prompt(args) -> dict:
    """Interactive mode: prompt user for inputs."""
    print("\n" + "=" * 65)
    print("  [FLOOD] INDIA FLOOD INUNDATION ENGINE")
    print("  Based on van den Bout et al. (2026) — FastFlood Methodology")
    print("=" * 65)
    print("\nThis engine implements the FastFlood steady-state algorithm")
    print("calibrated for Indian conditions (SCS-CN, IS 5477, CWC).\n")

    print("Select mode:")
    print("  1. Manual rainfall input")
    print("  2. Live weather forecast (Open-Meteo, free)")
    print("  3. Historical event (ERA5 reanalysis)")
    print("  4. Quick demo (synthetic data, no internet)")
    choice = input("\nEnter choice [1-4]: ").strip()

    mode_map = {"1": "manual", "2": "forecast", "3": "historical", "4": "demo"}
    mode = mode_map.get(choice, "demo")

    # Bounding box
    print("\nEnter bounding box (or press Enter for default — Lucknow, UP):")
    bbox_input = input("  min_lon min_lat max_lon max_lat: ").strip()
    if bbox_input:
        try:
            parts = [float(x) for x in bbox_input.split()]
            if len(parts) == 4:
                args.bbox = parts
        except ValueError:
            pass

    if args.bbox is None:
        args.bbox = list(DEFAULT_CONFIG["bbox"])

    if mode == "manual":
        rain_input = input(f"\nTotal rainfall (mm) [default=120]: ").strip()
        args.rain = float(rain_input) if rain_input else 120.0

        dur_input = input(f"Storm duration (hours) [default=12]: ").strip()
        args.dur = float(dur_input) if dur_input else 12.0

        amc_input = input(f"AMC condition [I/II/III, default=II]: ").strip().upper()
        if amc_input in ("I", "II", "III"):
            args.amc = amc_input

    elif mode == "historical":
        args.start_date = input("Start date (YYYY-MM-DD) [e.g. 2018-08-01]: ").strip()
        args.end_date = input("End date (YYYY-MM-DD) [e.g. 2018-08-20]: ").strip()

    args.mode = mode if mode != "demo" else "manual"
    if mode == "demo":
        args.no_download = True
        args.rain = args.rain or 150.0
        args.dur = args.dur or 12.0

    return args


