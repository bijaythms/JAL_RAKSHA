def run_historical_mode(engine: IndiaFloodEngine, args) -> dict:
    """Run simulation using ERA5 historical rainfall for a past event."""
    from data.weather_forecast import fetch_historical_rainfall, assess_flood_risk_from_forecast

    bbox = engine.bbox
    mid_lat = (bbox[1] + bbox[3]) / 2.0
    mid_lon = (bbox[0] + bbox[2]) / 2.0

    print(f"\n[DATE] Fetching ERA5 historical data: {args.start_date} → {args.end_date}")
    fc = fetch_historical_rainfall(mid_lat, mid_lon, args.start_date, args.end_date)

    assessment = assess_flood_risk_from_forecast(fc, duration_hr=args.forecast_hours or 24)
    print(f"   Historical rainfall: {assessment['total_rainfall_mm']}mm")
    print(f"   {assessment['imd_alert']}")

    return engine.run(
        rainfall_mm=assessment["total_rainfall_mm"],
        duration_hr=float(assessment["event_duration_hr"]),
    )


