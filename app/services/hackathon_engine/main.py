def _fix_proj_data():
    """Override PROJ_DATA to use rasterio's bundled PROJ database."""
    try:
        import importlib.util
        spec = importlib.util.find_spec("rasterio")
        if spec and spec.origin:
            rasterio_dir = Path(spec.origin).parent
            proj_db = rasterio_dir / "proj_data" / "proj.db"
            if proj_db.exists():
                proj_data_dir = str(proj_db.parent)
                os.environ["PROJ_DATA"] = proj_data_dir
                os.environ["PROJ_LIB"]  = proj_data_dir
    except Exception:
        pass

_fix_proj_data()

