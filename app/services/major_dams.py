def get_major_dams(q: Optional[str] = None,
                   state: Optional[str] = None,
                   region: Optional[str] = None,
                   material: Optional[str] = None) -> List[Dict[str, Any]]:
    """Filter major dams by search text, state, region, or dam material."""
    res = MAJOR_DAMS
    if q:
        query = q.lower().strip()
        res = [d for d in res if (
            query in d["name"].lower() or
            query in d["river"].lower() or
            query in d["state"].lower() or
            query in d["region_key"].lower() or
            query in d.get("notes", "").lower()
        )]
    if state and state.lower() != "all":
        res = [d for d in res if state.lower() in d["state"].lower()]
    if region and region.lower() != "all":
        res = [d for d in res if region.lower() in d["region_key"].lower()]
    if material and material.lower() != "all":
        res = [d for d in res if material.lower() == d["material"].lower()]
    return res

def get_dam_by_id(dam_id: str) -> Optional[Dict[str, Any]]:
    for d in MAJOR_DAMS:
        if d["id"] == dam_id:
            return d
    return None
